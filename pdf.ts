import { formatDate, inr, round2, todayISO } from './format';
import { Customer, Lang, Profile, Transaction } from './types';

/**
 * Statement PDF.
 * The page is drawn on a canvas (the browser shapes Devanagari correctly, which jsPDF's built-in fonts cannot do)
 * and each page is placed in the PDF as an image. Text in the PDF is therefore not selectable.
 */

const W = 1240; // A4 at 150 dpi
const H = 1754;
const M = 70;
const FONT = '"Noto Sans Devanagari","Plus Jakarta Sans","Segoe UI",system-ui,sans-serif';
const INK = '#0B1424';
const MUTED = '#5B6779';
const GOLD = '#B8902A';
const RED = '#B3261E';
const GREEN = '#17803D';
const LINE = '#D5DAE3';

const COL = { dateX: M, detailX: M + 190, udharR: M + 790, jamaR: M + 940, balR: W - M };
const DETAIL_W = 440;

interface Row {
  date: string;
  lines: string[];
  udhar: number;
  jama: number;
  balance: number;
}

export interface StatementInput {
  customer: Customer;
  txs: Transaction[];
  profile: Profile;
  lang: Lang;
  modeLabel: (m: string) => string;
}

function wrap(ctx: CanvasRenderingContext2D, text: string, maxW: number): string[] {
  const out: string[] = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const word of para.split(/\s+/).filter(Boolean)) {
      const trial = line ? line + ' ' + word : word;
      if (ctx.measureText(trial).width <= maxW) {
        line = trial;
        continue;
      }
      if (line) out.push(line);
      if (ctx.measureText(word).width <= maxW) {
        line = word;
      } else {
        // one very long word: break by characters
        let chunk = '';
        for (const ch of Array.from(word)) {
          if (ctx.measureText(chunk + ch).width > maxW && chunk) {
            out.push(chunk);
            chunk = ch;
          } else chunk += ch;
        }
        line = chunk;
      }
    }
    out.push(line);
  }
  return out.length ? out : [''];
}

function newCanvas(): { canvas: HTMLCanvasElement; ctx: CanvasRenderingContext2D } {
  const canvas = document.createElement('canvas');
  canvas.width = W;
  canvas.height = H;
  const ctx = canvas.getContext('2d')!;
  ctx.fillStyle = '#FFFFFF';
  ctx.fillRect(0, 0, W, H);
  ctx.textBaseline = 'alphabetic';
  return { canvas, ctx };
}

async function loadFonts(sample: string): Promise<void> {
  const fonts = (document as any).fonts;
  if (!fonts) return;
  try {
    await Promise.all([
      fonts.load(`400 24px ${FONT}`, sample),
      fonts.load(`700 24px ${FONT}`, sample),
      fonts.load(`600 24px ${FONT}`, sample),
    ]);
    await fonts.ready;
  } catch {
    /* fall back to system fonts */
  }
}

/** Lays the rows out into pages. Returns the rows for each page. */
function paginate(ctx: CanvasRenderingContext2D, rows: Row[]): Row[][] {
  const pages: Row[][] = [[]];
  let y = 680; // first page: header + summary + table header
  const bottom = H - 120;
  for (const r of rows) {
    const h = Math.max(1, r.lines.length) * 34 + 22;
    if (y + h > bottom) {
      pages.push([]);
      y = 260;
    }
    pages[pages.length - 1].push(r);
    y += h;
  }
  if (y + 150 > bottom) pages.push([]); // room for the closing balance box
  return pages;
}

export async function buildStatementPdf(input: StatementInput): Promise<Blob> {
  const { customer, profile, lang, modeLabel } = input;
  const tx = [...input.txs].sort((a, b) =>
    a.date === b.date ? (a.time + a.createdAt).localeCompare(b.time + b.createdAt) : a.date.localeCompare(b.date)
  );

  const hi = lang === 'hi';
  const L = {
    statement: hi ? 'खाता विवरण / Statement' : 'Account Statement',
    customer: hi ? 'ग्राहक' : 'Customer',
    phone: hi ? 'फ़ोन' : 'Phone',
    date: hi ? 'तारीख' : 'Date',
    details: hi ? 'विवरण' : 'Details',
    udhar: hi ? 'उधार (−)' : 'Udhar (−)',
    jama: hi ? 'जमा (+)' : 'Jama (+)',
    balance: hi ? 'शेष' : 'Balance',
    totalUdhar: hi ? 'कुल उधार' : 'Total udhar',
    totalJama: hi ? 'कुल जमा' : 'Total jama',
    closing: hi ? 'अंतिम शेष' : 'Closing balance',
    due: hi ? 'बाकी देना है' : 'Due',
    advance: hi ? 'अग्रिम जमा' : 'Advance',
    settled: hi ? 'चुकता' : 'Settled',
    none: hi ? 'कोई प्रविष्टि नहीं' : 'No entries yet',
    page: hi ? 'पृष्ठ' : 'Page',
    gen: hi ? 'HisabPro से बनाया गया' : 'Generated by HisabPro',
    bill: hi ? 'बिल' : 'Bill',
  };

  await loadFonts(
    [customer.name, profile.businessName, profile.address, ...tx.map((t) => t.description), Object.values(L).join('')].join(' ')
  );

  const scratch = newCanvas();
  scratch.ctx.font = `400 22px ${FONT}`;

  let running = 0;
  let totalUdhar = 0;
  let totalJama = 0;
  const rows: Row[] = tx.map((t) => {
    if (t.type === 'udhar') {
      running = round2(running + t.amount);
      totalUdhar = round2(totalUdhar + t.amount);
    } else {
      running = round2(running - t.amount);
      totalJama = round2(totalJama + t.amount);
    }
    const parts = [t.description, t.billNumber ? `${L.bill}: ${t.billNumber}` : '', modeLabel(t.paymentMode)].filter(Boolean);
    return {
      date: formatDate(t.date, lang),
      lines: wrap(scratch.ctx, parts.join(' · '), DETAIL_W - 16),
      udhar: t.type === 'udhar' ? t.amount : 0,
      jama: t.type === 'jama' ? t.amount : 0,
      balance: running,
    };
  });
  const closing = running;
  const pages = paginate(scratch.ctx, rows);
  const status = closing > 0 ? L.due : closing < 0 ? L.advance : L.settled;
  const statusColor = closing > 0 ? RED : closing < 0 ? GREEN : MUTED;

  const { jsPDF } = await import('jspdf');
  const pdf = new jsPDF({ unit: 'mm', format: 'a4', compress: true });

  pages.forEach((pageRows, pi) => {
    const { canvas, ctx } = newCanvas();
    let y: number;

    if (pi === 0) {
      // header band
      ctx.fillStyle = '#0A1526';
      ctx.fillRect(0, 0, W, 190);
      ctx.fillStyle = '#F3E5AB';
      ctx.font = `700 46px ${FONT}`;
      ctx.fillText(profile.businessName || 'HisabPro', M, 88);
      ctx.fillStyle = '#C9D3E3';
      ctx.font = `400 24px ${FONT}`;
      const sub = [profile.address, profile.phone].filter(Boolean).join('  ·  ');
      if (sub) ctx.fillText(sub.slice(0, 90), M, 132);
      ctx.fillStyle = GOLD;
      ctx.fillRect(0, 190, W, 6);

      ctx.fillStyle = INK;
      ctx.font = `700 36px ${FONT}`;
      ctx.fillText(L.statement, M, 270);
      ctx.fillStyle = MUTED;
      ctx.font = `400 24px ${FONT}`;
      ctx.textAlign = 'right';
      ctx.fillText(formatDate(todayISO(), lang), W - M, 270);
      ctx.textAlign = 'left';

      ctx.fillStyle = INK;
      ctx.font = `600 30px ${FONT}`;
      ctx.fillText(`${L.customer}: ${customer.name}`.slice(0, 60), M, 330);
      if (customer.phone) {
        ctx.fillStyle = MUTED;
        ctx.font = `400 24px ${FONT}`;
        ctx.fillText(`${L.phone}: ${customer.phone}`, M, 368);
      }

      // summary boxes
      const bw = (W - 2 * M - 40) / 3;
      const boxes: Array<[string, string, string]> = [
        [L.totalUdhar, inr(totalUdhar), RED],
        [L.totalJama, inr(totalJama), GREEN],
        [`${L.closing} · ${status}`, inr(Math.abs(closing)), statusColor],
      ];
      boxes.forEach(([label, value, color], i) => {
        const x = M + i * (bw + 20);
        ctx.fillStyle = '#F4F6FA';
        ctx.fillRect(x, 410, bw, 110);
        ctx.fillStyle = color;
        ctx.fillRect(x, 410, 6, 110);
        ctx.fillStyle = MUTED;
        ctx.font = `400 22px ${FONT}`;
        ctx.fillText(label, x + 24, 448);
        ctx.fillStyle = color;
        ctx.font = `700 38px ${FONT}`;
        ctx.fillText(value, x + 24, 498);
      });
      y = 680;
    } else {
      ctx.fillStyle = INK;
      ctx.font = `600 28px ${FONT}`;
      ctx.fillText(`${customer.name} · ${L.statement}`.slice(0, 70), M, 100);
      ctx.fillStyle = GOLD;
      ctx.fillRect(M, 118, W - 2 * M, 4);
      y = 260;
    }

    // table header
    const headY = y - 62;
    ctx.fillStyle = '#0A1526';
    ctx.fillRect(M, headY - 36, W - 2 * M, 56);
    ctx.fillStyle = '#FFFFFF';
    ctx.font = `700 22px ${FONT}`;
    ctx.fillText(L.date, COL.dateX + 12, headY);
    ctx.fillText(L.details, COL.detailX + 8, headY);
    ctx.textAlign = 'right';
    ctx.fillText(L.udhar, COL.udharR - 8, headY);
    ctx.fillText(L.jama, COL.jamaR - 8, headY);
    ctx.fillText(L.balance, COL.balR - 12, headY);
    ctx.textAlign = 'left';

    if (pi === 0 && rows.length === 0) {
      ctx.fillStyle = MUTED;
      ctx.font = `400 26px ${FONT}`;
      ctx.fillText(L.none, M + 12, y + 30);
    }

    pageRows.forEach((r, i) => {
      const h = Math.max(1, r.lines.length) * 34 + 22;
      if (i % 2 === 1) {
        ctx.fillStyle = '#F8F9FC';
        ctx.fillRect(M, y - 26, W - 2 * M, h);
      }
      ctx.fillStyle = INK;
      ctx.font = `400 22px ${FONT}`;
      ctx.fillText(r.date, COL.dateX + 12, y);
      ctx.fillStyle = INK;
      r.lines.forEach((ln, k) => ctx.fillText(ln, COL.detailX + 8, y + k * 34));
      ctx.textAlign = 'right';
      ctx.font = `600 22px ${FONT}`;
      if (r.udhar) {
        ctx.fillStyle = RED;
        ctx.fillText(inr(r.udhar), COL.udharR - 8, y);
      }
      if (r.jama) {
        ctx.fillStyle = GREEN;
        ctx.fillText(inr(r.jama), COL.jamaR - 8, y);
      }
      ctx.fillStyle = r.balance > 0 ? RED : r.balance < 0 ? GREEN : INK;
      ctx.fillText(inr(Math.abs(r.balance)), COL.balR - 12, y);
      ctx.textAlign = 'left';
      ctx.fillStyle = LINE;
      ctx.fillRect(M, y - 26 + h - 1, W - 2 * M, 1);
      y += h;
    });

    if (pi === pages.length - 1) {
      // closing balance box
      const by = y + 20;
      ctx.fillStyle = '#0A1526';
      ctx.fillRect(M, by, W - 2 * M, 90);
      ctx.fillStyle = '#F3E5AB';
      ctx.font = `700 28px ${FONT}`;
      ctx.fillText(`${L.closing} (${status})`, M + 24, by + 56);
      ctx.textAlign = 'right';
      ctx.font = `700 36px ${FONT}`;
      ctx.fillText(inr(Math.abs(closing)), W - M - 24, by + 58);
      ctx.textAlign = 'left';
    }

    // footer
    ctx.fillStyle = MUTED;
    ctx.font = `400 20px ${FONT}`;
    ctx.fillText(L.gen, M, H - 50);
    ctx.textAlign = 'right';
    ctx.fillText(`${L.page} ${pi + 1} / ${pages.length}`, W - M, H - 50);
    ctx.textAlign = 'left';

    if (pi > 0) pdf.addPage();
    pdf.addImage(canvas.toDataURL('image/jpeg', 0.85), 'JPEG', 0, 0, 210, 297, undefined, 'FAST');
  });

  return pdf.output('blob');
}
